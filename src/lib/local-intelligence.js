function normalize(value) {
  return String(value || '').toLowerCase().replace(/[\u064B-\u065F\u0670]/g, '').replace(/أ|إ|آ/g, 'ا').replace(/ة/g, 'ه').replace(/ى/g, 'ي');
}

function scorePack(pack, prompt, tool, mode) {
  const text = normalize(`${prompt} ${tool} ${mode}`);
  let score = 0;
  for (const trigger of pack.triggers) {
    const token = normalize(trigger);
    if (text.includes(token)) score += token.length > 5 ? 3 : 2;
  }
  if (tool === 'qa' && pack.id === 'qa') score += 8;
  if (tool === 'cv' || tool === 'cover') if (pack.id === 'career') score += 8;
  if (tool === 'email' || tool === 'rewrite') if (pack.id === 'writing') score += 7;
  if (tool === 'content' && pack.id === 'content') score += 8;
  if (tool === 'organize' || tool === 'tasks' || tool === 'plan') if (pack.id === 'productivity') score += 6;
  if (mode === 'study' && pack.id === 'study') score += 4;
  if (mode === 'work' && ['career','qa','writing','productivity'].includes(pack.id)) score += 2;
  return score;
}

export function retrieveLocalKnowledge({ prompt, tool = 'ask', mode = 'general', limit = 4 }) {
  return PACKS
    .map((pack) => ({ pack, score: scorePack(pack, prompt, tool, mode) }))
    .filter((item) => item.score > 0)
    .sort((a, b) => b.score - a.score)
    .slice(0, limit)
    .map((item) => item.pack);
}

function chooseFacts(packs, max = 10) {
  const seen = new Set();
  const out = [];
  for (const pack of packs) {
    for (const fact of pack.facts) {
      if (!seen.has(fact)) {
        seen.add(fact);
        out.push(fact);
      }
      if (out.length >= max) return out;
    }
  }
  return out;
}

function chooseMistakes(packs, max = 5) {
  return [...new Set(packs.flatMap((pack) => pack.mistakes || []))].slice(0, max);
}

function chooseSteps(packs, max = 7) {
  return [...new Set(packs.flatMap((pack) => pack.steps || []))].slice(0, max);
}

function isCurrentInfoRequest(prompt) {
  return /(اخر|احدث|اليوم|حاليا|current|latest|today|price|سعر الان|تحديثات|2026|2027)/i.test(String(prompt || ''));
}

export function localReasonedResponse({ prompt, tool = 'ask', mode = 'general', preferences = {} }) {
  const packs = retrieveLocalKnowledge({ prompt, tool, mode });
  const detail = preferences.responseStyle === 'concise' ? 'concise' : preferences.responseStyle === 'detailed' ? 'detailed' : 'normal';
  if (!packs.length) {
    return [
      '🧠 تحليل محلي',
      `الطلب: ${String(prompt || '').trim()}`,
      '',
      'تفكير عملي',
      ...GENERIC_REASONING.map((item) => `• ${item}`),
      '',
      'أفضل خطوة الآن',
      'حوّل الطلب إلى نتيجة محددة، ثم اختبر أصغر خطوة تقلل أكبر قدر من الغموض. إذا كانت الإجابة تعتمد على معلومة حديثة، أعد المحاولة عند عودة البحث الحي.'
    ].join('\n');
  }

  const facts = chooseFacts(packs, detail === 'concise' ? 5 : detail === 'detailed' ? 12 : 8);
  const mistakes = chooseMistakes(packs, detail === 'concise' ? 3 : 5);
  const steps = chooseSteps(packs, detail === 'concise' ? 5 : 7);
  const currentWarning = isCurrentInfoRequest(prompt)
    ? '⚠️ هذا الطلب يحتوي على جزء قد يكون متغيرًا زمنيًا. المعرفة المحلية تساعد في التحليل، لكن الأرقام/الإصدارات/الأسعار/آخر الأخبار تحتاج بحثًا حيًا للتأكيد.'
    : '';

  const sections = [
    '🧠 PathPilot Local Intelligence',
    currentWarning,
    '',
    'فهم الطلب',
    `الطلب: ${String(prompt || '').trim()}`,
    `المجالات الأقرب: ${packs.map((pack) => pack.id).join(' + ')}`,
    '',
    'الخلاصة',
    packs.map((pack) => `• ${pack.summary}`).join('\n'),
    '',
    'المعرفة المرتبطة',
    ...facts.map((fact) => `• ${fact}`),
    '',
    'طريقة المعالجة',
    ...steps.map((step, index) => `${index + 1}. ${step}`),
    '',
    'أخطاء يجب تجنبها',
    ...mistakes.map((mistake) => `• ${mistake}`),
    '',
    'مراجعة منطقية',
    ...GENERIC_REASONING.slice(0, detail === 'concise' ? 3 : 6).map((item) => `• ${item}`)
  ].filter(Boolean);

  return sections.join('\n');
}

