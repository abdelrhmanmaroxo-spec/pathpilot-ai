function normalize(value) {
  return String(value || '').toLowerCase().replace(/\s+/g, ' ').trim();
}

function score(entry, prompt, tool, mode) {
  const text = normalize(`${prompt} ${tool} ${mode}`);
  let total = 0;
  for (const trigger of entry.triggers) {
    const t = normalize(trigger);
    if (t && text.includes(t)) total += t.length >= 6 ? 4 : 2;
  }
  if (tool === 'research' && ['research-methods','critical-thinking','statistics'].includes(entry.id)) total += 3;
  if (tool === 'decide' && entry.id === 'decision-science') total += 5;
  if (tool === 'qa' && ['critical-thinking','cybersecurity','software-architecture'].includes(entry.id)) total += 2;
  if (mode === 'study' && ['learning','mathematics','statistics','physics','chemistry','biology','history','economics'].includes(entry.id)) total += 2;
  if (mode === 'work' && ['management','project-management','career','writing','product','marketing','sales'].includes(entry.id)) total += 2;
  return total;
}

export function retrieveEncyclopediaKnowledge({ prompt, tool = 'ask', mode = 'general', limit = 6 }) {
  return ENCYCLOPEDIA
    .map((entry) => ({ entry, score: score(entry, prompt, tool, mode) }))
    .filter((item) => item.score > 0)
    .sort((a, b) => b.score - a.score)
    .slice(0, limit)
    .map((item) => item.entry);
}

