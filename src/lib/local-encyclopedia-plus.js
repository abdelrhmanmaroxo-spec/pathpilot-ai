function normalize(value) {
  return String(value || '')
    .toLowerCase()
    .normalize('NFKD')
    .replace(/[\u064B-\u065F\u0670]/g, '')
    .replace(/[^\p{L}\p{N}+#.\-\s]/gu, ' ')
    .replace(/\s+/g, ' ')
    .trim();
}

function tokens(value) {
  return new Set(normalize(value).split(' ').filter((token) => token.length >= 2));
}

function lexicalScore(entry, prompt, tool, mode) {
  const text = normalize(`${prompt} ${tool} ${mode}`);
  const promptTokens = tokens(text);
  let score = 0;
  for (const trigger of entry.triggers) {
    const term = normalize(trigger);
    if (!term) continue;
    if (text.includes(term)) score += term.includes(' ') ? 7 : term.length >= 6 ? 5 : 3;
    else {
      const triggerTokens = tokens(term);
      let overlap = 0;
      for (const token of triggerTokens) if (promptTokens.has(token)) overlap += 1;
      if (overlap) score += overlap * 1.5;
    }
  }
  const semanticText = normalize(`${entry.summary} ${(entry.facts || []).slice(0, 4).join(' ')}`);
  const semanticTokens = tokens(semanticText);
  let overlap = 0;
  for (const token of promptTokens) if (semanticTokens.has(token)) overlap += 1;
  score += Math.min(6, overlap * 0.65);
  if (tool === 'research' && ['source-evaluation','information-retrieval','research-synthesis','scientific-method'].includes(entry.id)) score += 5;
  if (tool === 'decide' && ['decision-debugging','scenario-planning','optimization','bayesian-reasoning'].includes(entry.id)) score += 4;
  if (tool === 'qa' && ['root-cause-analysis','qa-strategy','testing-strategy','observability'].includes(entry.id)) score += 4;
  if (mode === 'study' && ['learning-science','study-planning','teaching','curriculum-design','project-based-learning'].includes(entry.id)) score += 3;
  if (mode === 'work' && ['operations','quality-management','stakeholder-management','strategy','career-strategy'].includes(entry.id)) score += 2;
  return score;
}

export function retrieveExpandedKnowledge({ prompt, tool = 'ask', mode = 'general', limit = 8, seedIds = [] }) {
  const seedSet = new Set(seedIds);
  return EXPANDED_ENCYCLOPEDIA
    .map((entry) => {
      let score = lexicalScore(entry, prompt, tool, mode);
      if (seedSet.has(entry.id)) score += 8;
      if (entry.related?.some((id) => seedSet.has(id))) score += 3;
      return { entry, score };
    })
    .filter((item) => item.score > 0)
    .sort((a, b) => b.score - a.score)
    .slice(0, limit)
    .map((item) => item.entry);
}

